# 10 categories x choose(72,2) = 25,560 pair combinations.
OPTIONS = tuple(
    tuple(dict.fromkeys(fmt.format(x=topic) for topic in topics for fmt in formats))
    for _name, topics, formats in THEMES
)
PAIR_COUNTS = tuple(len(opts)*(len(opts)-1)//2 for opts in OPTIONS)
TOTAL = sum(PAIR_COUNTS)


def choices_at(index):
    """Return (category, option_a, option_b), stable under process restarts."""
    if not 0 <= index < TOTAL:
        raise ValueError("invalid pair index")
    for category, (name, _topics, _formats) in enumerate(THEMES):
        count = PAIR_COUNTS[category]
        if index >= count:
            index -= count
            continue
        opts = OPTIONS[category]
        # Triangular pair enumeration avoids loading 25k records into memory.
        for a in range(len(opts)-1):
            span = len(opts)-a-1
            if index < span:
                return name, opts[a], opts[a+1+index]
            index -= span
    raise AssertionError("inconsistent category totals")
